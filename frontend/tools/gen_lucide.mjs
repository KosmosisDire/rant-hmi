/* Regenerate src/lucide.ts from a lucide-static package directory:
 *
 *   npm pack lucide-static && tar xzf lucide-static-*.tgz
 *   node tools/gen_lucide.mjs path/to/package
 *
 * Each icon becomes the INNER markup of its 24x24 stroked SVG (the same shape
 * icons.ts uses), keyed by its kebab-case file name, so `:icon-name:` in any
 * text resolves without fetching anything at run time. */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = process.argv[2];
if (!pkg) {
  console.error("usage: node tools/gen_lucide.mjs <lucide-static package dir>");
  process.exit(1);
}
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
const iconsDir = join(pkg, "icons");

const entries = [];
for (const file of readdirSync(iconsDir).sort()) {
  if (!file.endsWith(".svg")) continue;
  const name = file.slice(0, -4);
  const svg = readFileSync(join(iconsDir, file), "utf8");
  const open = svg.indexOf(">", svg.indexOf("<svg"));
  const close = svg.lastIndexOf("</svg>");
  const inner = svg
    .slice(open + 1, close)
    .replace(/\s+/g, " ")
    .replace(/ \/>/g, "/>")
    .replace(/> </g, "><")
    .trim();
  entries.push(`  "${name}": '${inner.replace(/'/g, "\\'")}',`);
}

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "lucide.ts");
writeFileSync(
  out,
  `/* GENERATED by tools/gen_lucide.mjs from lucide-static ${version}. Do not edit.\n` +
    ` * The full Lucide set: each value is the inner markup of a 24x24 stroked icon,\n` +
    ` * so \`:name:\` in any text field renders it inline (rich.ts). */\n\n` +
    `export const LUCIDE: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`wrote src/lucide.ts (${entries.length} icons, lucide-static ${version})`);
